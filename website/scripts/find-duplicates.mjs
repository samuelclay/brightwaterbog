#!/usr/bin/env node
// Flag near-duplicate photos among the era-"now" set and write
// src/data/duplicates.json, which PhotoStrip reads to draw a red border and a
// short ID on each suspect. Review tool only — it never deletes anything.
//
//   node scripts/find-duplicates.mjs [--distance 12]
//
// Scope is deliberately only era "now": the then/construction/drawings scans
// are the irreplaceable record and are never flagged, however alike they look.
//
// Similarity is a 64-bit dHash (9x8 grayscale, each pixel compared to its right
// neighbour) scored by Hamming distance — robust to exposure and small framing
// shifts, which is what separates two frames of one subject from two subjects.
// Clips are hashed on their poster still, so a clip can pair with a still of
// the same shot; that's usually the interesting case, not a false positive.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(HERE, "..");
const PHOTOS = path.join(SITE, "..", "photos");
const OUT = path.join(SITE, "src", "data", "duplicates.json");

const argIdx = process.argv.indexOf("--distance");
const MAX_DISTANCE = Number(argIdx > -1 ? process.argv[argIdx + 1] : 12);
const DRY = process.argv.includes("--dry-run");

async function dhash(file) {
  const raw = await sharp(file)
    .rotate()
    .greyscale()
    .resize(9, 8, { fit: "fill" })
    .raw()
    .toBuffer();
  let bits = 0n;
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      bits = (bits << 1n) | (raw[y * 9 + x] > raw[y * 9 + x + 1] ? 1n : 0n);
    }
  }
  return bits;
}

const hamming = (a, b) => {
  let v = a ^ b;
  let n = 0;
  while (v) {
    n += Number(v & 1n);
    v >>= 1n;
  }
  return n;
};

const photos = JSON.parse(await readFile(path.join(SITE, "src", "data", "photos.json"), "utf8"));

const items = [];
for (const [slug, entries] of Object.entries(photos)) {
  for (const p of entries) {
    if (p.era !== "now") continue; // then/construction/drawings are kept whole
    items.push({
      slug,
      key: p.key,
      file: path.join(PHOTOS, p.key),
      date: p.date ?? "",
      isClip: Boolean(p.video),
      name: path.basename(p.key),
    });
  }
}

const POOL = 8;
let cursor = 0;
await Promise.all(
  Array.from({ length: POOL }, async () => {
    while (cursor < items.length) {
      const it = items[cursor++];
      it.hash = await dhash(it.file);
    }
  }),
);

// Union-find per stop, so a run of five burst frames forms one group rather
// than four overlapping pairs.
const parent = new Map(items.map((it) => [it.key, it.key]));
const find = (k) => (parent.get(k) === k ? k : (parent.set(k, find(parent.get(k))), parent.get(k)));
const union = (a, b) => parent.set(find(a), find(b));

const bySlug = new Map();
for (const it of items) {
  if (!bySlug.has(it.slug)) bySlug.set(it.slug, []);
  bySlug.get(it.slug).push(it);
}
for (const group of bySlug.values()) {
  for (let i = 0; i < group.length; i++) {
    for (let j = i + 1; j < group.length; j++) {
      if (hamming(group[i].hash, group[j].hash) <= MAX_DISTANCE) union(group[i].key, group[j].key);
    }
  }
}

const clusters = new Map();
for (const it of items) {
  const root = find(it.key);
  if (!clusters.has(root)) clusters.set(root, []);
  clusters.get(root).push(it);
}

const LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const label = (n) => (n < 26 ? LETTERS[n] : LETTERS[Math.floor(n / 26) - 1] + LETTERS[n % 26]);

const order = Object.keys(photos);
const dupes = [...clusters.values()]
  .filter((g) => g.length > 1)
  .sort(
    (a, b) =>
      order.indexOf(a[0].slug) - order.indexOf(b[0].slug) || a[0].date.localeCompare(b[0].date),
  );

const marks = {};
const groups = [];
dupes.forEach((group, gi) => {
  group.sort((a, b) => a.date.localeCompare(b.date));
  const tag = label(gi);
  groups.push({
    group: tag,
    stop: group[0].slug,
    members: group.map((it, i) => ({
      id: `${tag}${i + 1}`,
      kind: it.isClip ? "clip" : "photo",
      file: it.name,
      key: it.key,
    })),
  });
  group.forEach((it, i) => (marks[it.key] = `${tag}${i + 1}`));
});

if (!DRY) {
  await writeFile(
    OUT,
    JSON.stringify(
      {
        _readme:
          "Generated by scripts/find-duplicates.mjs — review markers only, nothing is deleted. Keys are photo keys; values are the ID drawn on the red-bordered frame. Empty `marks` to clear the markers, then `npm run catalog` is NOT needed — just restart the dev server.",
        generated: { distance: MAX_DISTANCE, scannedNowPhotos: items.length },
        groups,
        marks,
      },
      null,
      2,
    ) + "\n",
  );
}

console.log(
  `find-duplicates (distance ≤ ${MAX_DISTANCE}): ${items.length} "now" items scanned, ` +
    `${dupes.length} groups covering ${Object.keys(marks).length} items` +
    (DRY ? " (dry run)" : " → src/data/duplicates.json"),
);
for (const g of groups) {
  const kinds = g.members.map((m) => `${m.id}${m.kind === "clip" ? "*" : ""}`).join(" ");
  console.log(`  ${g.group.padEnd(2)} ${g.stop.padEnd(26)} ${g.members.length}×  ${kinds}`);
}
